def wire_string(value):
    raw = value if isinstance(value, bytes) else value.encode("utf-8")
    return struct.pack("<Q", len(raw)) + raw


def wire_value(type_id, value):
    if type_id == 8:
        return struct.pack("<I", 8) + wire_string(value)
    if type_id == 9:
        item_type, items = value
        body = (b"".join(wire_string(v) for v in items) if item_type == 8 else
                struct.pack("<" + SCALAR_WIRE[item_type] * len(items), *items))
        return struct.pack("<IIQ", 9, item_type, len(items)) + body
    return struct.pack("<I" + SCALAR_WIRE[type_id], type_id, value)


def wire_metadata(entries):
    return b"".join(wire_string(key) + wire_value(kind, value) for key, kind, value in entries)


def fixture(tensors=(), metadata=(), *, alignment=32, payload_size=512, pad=True):
    header = struct.pack("<IIQQ", 0x46554747, 3, len(tensors), len(metadata)) + wire_metadata(metadata)
    for name, shape, type_id, offset in tensors:
        header += wire_string(name) + struct.pack("<I", len(shape))
        header += struct.pack("<" + "Q" * len(shape), *shape) + struct.pack("<IQ", type_id, offset)
    raw = header + (b"\0" * (-len(header) % alignment) if pad else b"") + b"\xa5" * payload_size
    return raw, len(header)


def large_array_fixture(count, *, alignment=32, payload_size=64):
    """A one-u8-array header; items are written as bytes so the test stays small."""
    header = struct.pack("<IIQQ", 0x46554747, 3, 0, 1) + wire_string("array")
    header += struct.pack("<IIQ", 9, 0, count) + b"\x01" * count
    raw = header + b"\0" * (-len(header) % alignment) + b"\xa5" * payload_size
    return raw, len(header)


