    def test_raw_fd_read_sizes_no_prefetch_and_read_only_open(self):
        path, raw, end = self.write_fixture(tensors=BASE_SPECS, payload_size=576)
        original_fdopen, original_open = os.fdopen, os.open
        calls, opened, handles = [], [], []

        class Observed:
            def __init__(self, handle):
                self.handle = handle
            def __enter__(self):
                return self
            def __exit__(self, *args):
                return self.handle.__exit__(*args)
            def fileno(self):
                return self.handle.fileno()
            def read(self, size):
                calls.append((self.handle.tell(), size))
                if size < 0 or self.handle.tell() + size > end:
                    raise AssertionError("local raw read escaped logical header")
                return self.handle.read(size)

        def fdopen(fd, mode, buffering):
            self.assertEqual((mode, buffering), ("rb", 0))
            handle = original_fdopen(fd, mode, buffering=buffering)
            handles.append(handle)
            return Observed(handle)

        def opening(path, flags):
            opened.append(flags)
            return original_open(path, flags)

        path.chmod(0o444)
        before = os.stat(path)
        with mock.patch.object(I.os, "fdopen", side_effect=fdopen), mock.patch.object(I.os, "open", side_effect=opening):
            doc = I.inventory([str(path)])
        after = os.stat(path)
        self.assertEqual(I._snapshot(before), I._snapshot(after))
        self.assertEqual(stat.S_IMODE(after.st_mode), 0o444)
        self.assertEqual(path.read_bytes(), raw)
        self.assertEqual(sum(size for _, size in calls), end)
        self.assertTrue(all(handle.closed for handle in handles))
        self.assertEqual(len(opened), 1)
        self.assertTrue(opened[0] & os.O_NOFOLLOW and opened[0] & os.O_NONBLOCK)
        self.assertFalse(opened[0] & (os.O_WRONLY | os.O_RDWR | os.O_TRUNC | os.O_CREAT))
        self.assertEqual(doc["shards"][0]["header_end_bytes"], end)

